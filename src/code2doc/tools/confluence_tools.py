class GetPageByTitleTool(BaseTool):
    """Tool to get a Confluence page by title."""

    @property
    def name(self) -> str:
        return "get_page_by_title"

    @property
    def description(self) -> str:
        return "Get a Confluence page by its title in a specific space"

    @property
    def parameters(self) -> dict[str, dict[str, Any]]:
        return {
            "title": {
                "description": "Exact page title",
                "type": "string",
                "required": True,
            },
            "space_key": {
                "description": "Confluence space key",
                "type": "string",
                "required": False,
            },
        }

    def execute(self, **kwargs: Any) -> ToolResult:
        try:
            client = ConfluenceClient.get_instance()
            page = client.get_page_by_title(
                title=kwargs["title"],
                space_key=kwargs.get("space_key"),
            )

            if page is None:
                logger.warning(
                    f"Page not found: {kwargs['title']} - it will be created if using find_or_create_page"
                )
                return ToolResult.success(
                    {
                        "status": "not_found",
                        "title": kwargs["title"],
                        "message": f"Page '{kwargs['title']}' does not exist yet",
                    }
                )

            return ToolResult.success(
                {
                    "status": "found",
                    "id": page["id"],
                    "title": page["title"],
                    "version": page["version"]["number"],
                    "content": page.get("body", {}).get("storage", {}).get("value", ""),
                }
            )
        except ApiError as e:
            return ToolResult.failure(f"Confluence API error: {str(e)}")
        except Exception as e:
            return ToolResult.failure(f"Failed to get page by title: {str(e)}")
